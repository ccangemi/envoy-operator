#!/usr/bin/env bash
# Generates config/rbac/role.yaml, the ClusterRole of the operator, from the
# chart. hack/update-upstream.sh runs it after each chart update.
#
#   hack/generate-rbac.sh           write config/rbac/role.yaml
#   hack/generate-rbac.sh --check   fail if config/rbac/role.yaml is not up to date
#
# The script renders the operator chart for each value set below and keeps the
# union. hack/rbac.py explains which permissions the operator needs and why.
# It needs no cluster and no network.

# shellcheck source=hack/lib.sh
source "$(dirname "$0")/lib.sh"
require_tools HELM YQ

# Value sets that together render every kind of object and every role that the
# operator may install: the defaults, and the optional features turned on.
VALUE_SETS=(
  ""
  "--set=gateway-helm.topologyInjector.enabled=true
   --set=gateway-helm.config.envoyGateway.provider.kubernetes.deploy.type=GatewayNamespace
   --set=gateway-helm.hpa.enabled=true
   --set=gateway-helm.podDisruptionBudget.minAvailable=1"
)

ROLE=$ROOT_DIR/config/rbac/role.yaml
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

i=0
for set in "${VALUE_SETS[@]}"; do
  # shellcheck disable=SC2086 # the value set is a list of arguments
  "$HELM" template "$CR_NAME" "$CHART_DIR" --namespace "$OPERATOR_NAMESPACE" --include-crds $set \
    >"$work/render-$i.yaml" || fail "cannot render the chart with: ${set:-the defaults}"
  i=$((i + 1))
done
"$YQ" ea -o json -I0 '[.]' "$work"/render-*.yaml >"$work/manifests.json"

plural=$(tr '[:upper:]' '[:lower:]' <<<"$CR_KIND")s
cat >"$work/base.json" <<JSON
[
  {"apiGroups": ["$CR_GROUP"], "resources": ["$plural", "$plural/status", "$plural/finalizers"],
   "verbs": ["create", "delete", "get", "list", "patch", "update", "watch"]},
  {"apiGroups": [""], "resources": ["secrets"], "verbs": ["create", "delete", "get", "list", "patch", "update", "watch"]},
  {"apiGroups": [""], "resources": ["events"], "verbs": ["create", "patch"]},
  {"apiGroups": [""], "resources": ["namespaces"], "verbs": ["get"]}
]
JSON

{
  echo "# Generated by hack/generate-rbac.sh from the chart. Do not edit."
  echo "# The operator needs full control of every kind of object that the chart"
  echo "# installs, and every permission that the roles of the chart grant"
  echo "# (Kubernetes privilege escalation prevention). See hack/rbac.py."
  python3 -I "$ROOT_DIR/hack/rbac.py" "$work/manifests.json" "$work/base.json" | "$YQ" -p json -o yaml -P
} >"$work/role.yaml"

if [[ ${1:-} == --check ]]; then
  diff -u "$ROLE" "$work/role.yaml" || fail "config/rbac/role.yaml is not up to date. Run 'hack/generate-rbac.sh'."
  log "config/rbac/role.yaml is up to date"
else
  mv "$work/role.yaml" "$ROLE"
  log "wrote ${ROLE#"$ROOT_DIR"/}"
fi
